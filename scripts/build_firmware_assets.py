def build_sprites_header(sprites_doc: dict, out_path: Path) -> dict[str, int]:
    """Bake sprite sheets into RGB565 + 1bpp mask tables.

    Returns {sprite name: index into kSprites} for the scene generator.
    """
    sprites = sprites_doc.get("sprites")
    if not isinstance(sprites, dict) or not sprites:
        raise SystemExit("sprites.json: missing or empty 'sprites' object.")
    sprite_index = {name: i for i, name in enumerate(sprites)}

    entries: list[tuple[str, str, int, int, int, int, int, int, list[int], bytearray]] = []
    for name, spec in sprites.items():
        ctx = f"sprites.json: sprite '{name}'"
        try:
            src = REPO_ROOT / spec["src"]
            frame_w = int(spec["frameWidth"])
            frame_h = int(spec["frameHeight"])
            frames = int(spec["frames"])
            fps = int(spec["fps"])
        except (KeyError, TypeError, ValueError) as exc:
            raise SystemExit(f"{ctx}: bad or missing field ({exc!r}).") from None
        if frames < 1 or frame_w < 1 or frame_h < 1:
            raise SystemExit(f"{ctx}: frameWidth/frameHeight/frames must be >= 1.")
        if not src.exists():
            raise SystemExit(f"{ctx}: sheet not found: {src}")

        sheet_w = frame_w * frames
        img = Image.open(src).convert("RGBA")
        if img.size != (sheet_w, frame_h):
            raise SystemExit(
                f"{ctx}: {src.name} is {img.size[0]}x{img.size[1]}, expected "
                f"frameWidth*frames x frameHeight = {sheet_w}x{frame_h}."
            )

        px = img.load()
        row_bytes = (sheet_w + 7) // 8
        pixels: list[int] = []
        mask = bytearray(row_bytes * frame_h)
        for y in range(frame_h):
            for x in range(sheet_w):
                r, g, b, a = px[x, y]
                if a >= 128:
                    pixels.append(rgb_to_565(r, g, b))
                    mask[y * row_bytes + x // 8] |= 1 << (7 - x % 8)
                else:
                    pixels.append(0x0000)
        entries.append(
            (name, camel_case(name), frame_w, frame_h, frames, fps, sheet_w,
             row_bytes, pixels, mask)
        )

    transport = sprites_doc.get("transport_default")
    if not isinstance(transport, list) or not transport:
        raise SystemExit("sprites.json: missing or empty 'transport_default' array.")
    for t in transport:
        if t not in sprite_index:
            raise SystemExit(f"sprites.json: transport_default names unknown sprite {t!r}.")

    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w", encoding="utf-8") as f:
        write_header_preamble(
            f, "scripts/build_firmware_assets.py",
            "data/sprites.json + assets/sprites/*.png",
            ('"game_data_types.h"',),
        )
        f.write("namespace road_east::assets {\n\n")
        for (name, camel, frame_w, frame_h, frames, fps, sheet_w,
             row_bytes, pixels, mask) in entries:
            f.write(f"// {name}: {frames} frame(s) of {frame_w}x{frame_h}, sheet {sheet_w}x{frame_h}.\n")
            f.write("// RGB565, row-major, sheetWidth * frameHeight; 0x0000 where the mask bit is clear.\n")
            f.write(f"inline constexpr uint16_t kSprite{camel}Pixels[{len(pixels)}] = {{\n")
            for i in range(0, len(pixels), 12):
                chunk = pixels[i : i + 12]
                f.write("    " + ", ".join(f"0x{v:04X}" for v in chunk) + ",\n")
            f.write("};\n\n")
            f.write(f"// 1bpp opacity mask, MSB-first, {row_bytes} byte(s) per row; bit set = opaque.\n")
            f.write(f"inline constexpr uint8_t kSprite{camel}Mask[{len(mask)}] = {{\n")
            for i in range(0, len(mask), 16):
                chunk = mask[i : i + 16]
                f.write("    " + ", ".join(f"0x{b:02X}" for b in chunk) + ",\n")
            f.write("};\n\n")

        f.write(f"inline constexpr int kSpriteCount = {len(entries)};\n\n")
        f.write("// Order matches data/sprites.json \"sprites\" — indices are the contract.\n")
        f.write(f"inline constexpr {DATA_NS}::SpriteDef kSprites[kSpriteCount] = {{\n")
        f.write("    // name, frameWidth, frameHeight, frames, fps, sheetWidth, pixels, mask\n")
        for (name, camel, frame_w, frame_h, frames, fps, sheet_w, *_rest) in entries:
            f.write(
                f"    {{ {c_string(name)}, {frame_w}, {frame_h}, {frames}, {fps}, "
                f"{sheet_w}, kSprite{camel}Pixels, kSprite{camel}Mask }},\n"
            )
        f.write("};\n\n")
        f.write("// Indices into kSprites for data/sprites.json \"transport_default\".\n")
        f.write(f"inline constexpr int kTransportSpriteCount = {len(transport)};\n")
        values = ", ".join(str(sprite_index[t]) for t in transport)
        names = ", ".join(transport)
        f.write(
            f"inline constexpr int8_t kTransportSprites[kTransportSpriteCount] = "
            f"{{ {values} }};  // {names}\n\n"
        )
        f.write("}  // namespace road_east::assets\n")
    return sprite_index


