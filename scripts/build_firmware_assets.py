ANCHOR_MAP = {
    "top-left": "SpriteAnchor::TopLeft",
    "center-bottom": "SpriteAnchor::CenterBottom",
    "left-bottom": "SpriteAnchor::LeftBottom",
}


def scene_layer_initializer(layer: dict, sprite_index: dict[str, int], ctx: str) -> str:
    """One SceneLayer brace-initialiser, all fields in declared order."""
    ltype = layer.get("type")
    if ltype == "rect":
        type_v = f"{DATA_NS}::LayerType::Rect"
        color = parse_css_color(layer["color"], ctx) if "color" in layer else 0
        # Sprite fields: harmless defaults for rect layers.
        sprite_v = f"{DATA_NS}::kSpriteHero"
        anchor_v = f"{DATA_NS}::SpriteAnchor::TopLeft"
        tile_v = "false"
        scroll = 0
        spacing = 0
        animated_v = "true"
        freeze = -1
    elif ltype == "sprite":
        type_v = f"{DATA_NS}::LayerType::Sprite"
        color = 0  # Rect-only field; harmless default for sprite layers.
        sprite_name = layer.get("sprite")
        if sprite_name == "${hero}":
            sprite_v = f"{DATA_NS}::kSpriteHero"
        elif sprite_name in sprite_index:
            sprite_v = f"{sprite_index[sprite_name]} /*{sprite_name}*/"
        else:
            raise SystemExit(f"{ctx}: unknown sprite {sprite_name!r}.")
        anchor_name = layer.get("anchor", "top-left")
        if anchor_name not in ANCHOR_MAP:
            raise SystemExit(f"{ctx}: unknown anchor {anchor_name!r}.")
        anchor_v = f"{DATA_NS}::{ANCHOR_MAP[anchor_name]}"
        tile_v = "true" if layer.get("tile", False) else "false"
        scroll = int(layer.get("scrollSpeed", 0))
        spacing = int(layer.get("spacing", 0))
        # SceneLayer stores animationSpeed as a bool, which is all the PWA
        # content uses. Refuse anything else rather than silently rounding a
        # half-speed layer up to full speed.
        anim_speed = layer.get("animationSpeed", 1)
        if anim_speed not in (0, 1):
            raise SystemExit(
                f"{ctx}: animationSpeed={anim_speed!r} is not representable — "
                "SceneLayer.animated is a flag; widen it to fixed-point first."
            )
        animated_v = "true" if anim_speed else "false"
        freeze = check_i8(layer.get("freezeFrame", -1), f"{ctx}: freezeFrame")
    else:
        raise SystemExit(f"{ctx}: unknown layer type {ltype!r}.")

    x = int(layer.get("x", 0))
    y = int(layer.get("y", 0))
    w = int(layer.get("w", 0))
    h = int(layer.get("h", 0))
    return (
        f"{{ {type_v}, {x}, {y}, {w}, {h}, 0x{color:04X}, "
        f"{sprite_v}, {anchor_v}, {tile_v}, {scroll}, {spacing}, {animated_v}, {freeze} }}"
    )


def build_scenes_header(
    scenes_doc: dict, sprite_index: dict[str, int], out_path: Path
) -> dict[str, int]:
    """Bake scene layer tables. Returns {scene id: index into kScenes}."""
    scenes = scenes_doc.get("scenes")
    if not isinstance(scenes, dict) or not scenes:
        raise SystemExit("scenes.json: missing or empty 'scenes' object.")
    scene_index = {name: i for i, name in enumerate(scenes)}

    default_scene = scenes_doc.get("default_scene")
    if default_scene not in scene_index:
        raise SystemExit(f"scenes.json: default_scene {default_scene!r} is not a scene.")

    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w", encoding="utf-8") as f:
        write_header_preamble(
            f, "scripts/build_firmware_assets.py", "data/scenes.json",
            ('"game_data_types.h"',),
        )
        f.write("namespace road_east::assets {\n\n")
        f.write(f"// Layer fields, in {DATA_NS}::SceneLayer order:\n")
        f.write("//   type, x, y, w, h, color, sprite, anchor, tile, scrollSpeed, spacing, animated, freezeFrame\n\n")
        for name, spec in scenes.items():
            ctx = f"scenes.json: scene '{name}'"
            layers = spec.get("layers")
            if not isinstance(layers, list) or not layers:
                raise SystemExit(f"{ctx}: missing or empty 'layers'.")
            camel = camel_case(name)
            f.write(f"inline constexpr {DATA_NS}::SceneLayer kScene{camel}Layers[{len(layers)}] = {{\n")
            for i, layer in enumerate(layers):
                init = scene_layer_initializer(layer, sprite_index, f"{ctx} layer {i}")
                f.write(f"    {init},\n")
            f.write("};\n\n")

        f.write(f"inline constexpr int kSceneCount = {len(scenes)};\n\n")
        f.write("// Order matches data/scenes.json \"scenes\" — indices are the contract.\n")
        f.write(f"inline constexpr {DATA_NS}::SceneDef kScenes[kSceneCount] = {{\n")
        f.write("    // id, background, layers, layerCount\n")
        for name, spec in scenes.items():
            if "background" not in spec:
                raise SystemExit(f"scenes.json: scene '{name}': missing 'background'.")
            bg = parse_css_color(spec["background"], f"scenes.json: scene '{name}' background")
            camel = camel_case(name)
            f.write(f"    {{ {c_string(name)}, 0x{bg:04X}, kScene{camel}Layers, {len(spec['layers'])} }},\n")
        f.write("};\n\n")
        f.write(
            f"inline constexpr int8_t kDefaultSceneIndex = {scene_index[default_scene]};"
            f"  // {default_scene}\n\n"
        )
        f.write("}  // namespace road_east::assets\n")
    return scene_index


