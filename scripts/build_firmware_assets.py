def scene_index_expr(name: object, scene_index: dict[str, int], ctx: str) -> str:
    if name not in scene_index:
        raise SystemExit(f"{ctx}: unknown scene {name!r}.")
    return f"{scene_index[name]} /*{name}*/"


def build_events_header(
    events_doc: object, scene_index: dict[str, int], out_path: Path
) -> None:
    if not isinstance(events_doc, list) or not events_doc:
        raise SystemExit("events.json: expected a non-empty array of events.")

    event_ids: set[str] = set()
    for event in events_doc:
        eid = event.get("id") if isinstance(event, dict) else None
        if not isinstance(eid, str) or not eid:
            raise SystemExit(f"events.json: event without a valid 'id': {event!r}.")
        if eid in event_ids:
            raise SystemExit(f"events.json: duplicate event id {eid!r}.")
        event_ids.add(eid)

    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w", encoding="utf-8") as f:
        write_header_preamble(
            f, "scripts/build_firmware_assets.py", "data/events.json",
            ('"game_data_types.h"',),
        )
        f.write("namespace road_east::assets {\n\n")
        for event in events_doc:
            eid = event["id"]
            ctx = f"events.json: event '{eid}'"
            choices = event.get("choices")
            if not isinstance(choices, list) or not choices:
                raise SystemExit(f"{ctx}: missing or empty 'choices'.")
            camel = camel_case(eid)
            f.write(f"inline constexpr {DATA_NS}::ChoiceDef kEvent{camel}Choices[{len(choices)}] = {{\n")
            for i, choice in enumerate(choices):
                cctx = f"{ctx} choice {i}"
                action = choice.get("action")
                if not isinstance(action, str) or not action:
                    raise SystemExit(f"{cctx}: missing 'action'.")
                next_id = choice.get("next_id")
                if next_id not in event_ids:
                    raise SystemExit(f"{cctx}: next_id {next_id!r} is not an event id.")
                # Three-way "scene": absent = inherit, null = none, name = index.
                if "scene" not in choice:
                    scene_expr = f"{DATA_NS}::kSceneInherit"
                elif choice["scene"] is None:
                    scene_expr = f"{DATA_NS}::kSceneNone"
                else:
                    scene_expr = scene_index_expr(choice["scene"], scene_index, cctx)
                if choice.get("result_scene") is None:
                    result_scene_expr = f"{DATA_NS}::kSceneNone"
                else:
                    result_scene_expr = scene_index_expr(
                        choice["result_scene"], scene_index, f"{cctx} result_scene"
                    )
                if choice.get("transport_mod") is None:
                    transport_expr = f"{DATA_NS}::kTransportKeep"
                else:
                    transport_expr = str(check_i8(choice["transport_mod"], f"{cctx}: transport_mod"))
                food = check_i8(choice.get("food_mod", 0), f"{cctx}: food_mod")
                hp = check_i8(choice.get("hp_mod", 0), f"{cctx}: hp_mod")
                mood = check_i8(choice.get("mood_mod", 0), f"{cctx}: mood_mod")
                f.write("    {\n")
                f.write(f"        /*action=*/{c_string(action)},\n")
                f.write(
                    f"        /*transportMod=*/{transport_expr}, /*foodMod=*/{food}, "
                    f"/*hpMod=*/{hp}, /*moodMod=*/{mood},\n"
                )
                f.write(f"        /*nextId=*/{c_string(next_id)},\n")
                f.write(f"        /*scene=*/{scene_expr},\n")
                f.write(f"        /*resultTitle=*/{c_string_or_null(choice.get('result_title'), cctx)},\n")
                f.write(f"        /*resultText=*/{c_string_or_null(choice.get('result_text'), cctx)},\n")
                f.write(f"        /*resultScene=*/{result_scene_expr},\n")
                f.write(f"        /*continueText=*/{c_string_or_null(choice.get('continue_text'), cctx)},\n")
                f.write("    },\n")
            f.write("};\n\n")

        f.write(f"inline constexpr int kEventCount = {len(events_doc)};\n\n")
        f.write("// Order matches data/events.json. next_id is resolved by id at runtime.\n")
        f.write(f"inline constexpr {DATA_NS}::EventDef kEvents[kEventCount] = {{\n")
        for event in events_doc:
            eid = event["id"]
            ctx = f"events.json: event '{eid}'"
            text = event.get("text")
            if not isinstance(text, str) or not text:
                raise SystemExit(f"{ctx}: missing 'text'.")
            if event.get("scene") is None:
                scene_expr = f"{DATA_NS}::kSceneNone"
            else:
                scene_expr = scene_index_expr(event["scene"], scene_index, ctx)
            fuel = check_i8(event.get("fuel_mod", 0), f"{ctx}: fuel_mod")
            camel = camel_case(eid)
            f.write("    {\n")
            f.write(f"        /*id=*/{c_string(eid)},\n")
            f.write(f"        /*text=*/{c_string(text)},\n")
            f.write(f"        /*hint=*/{c_string_or_null(event.get('hint'), ctx)},\n")
            f.write(f"        /*scene=*/{scene_expr},\n")
            f.write(
                f"        /*unlockFriend=*/{c_string_or_null(event.get('unlock_friend'), ctx)}, "
                f"/*unlockFriend2=*/{c_string_or_null(event.get('unlock_friend_2'), ctx)},\n"
            )
            f.write(f"        /*fuelMod=*/{fuel},\n")
            f.write(f"        /*choices=*/kEvent{camel}Choices, /*choiceCount=*/{len(event['choices'])},\n")
            f.write("    },\n")
        f.write("};\n\n")
        f.write("}  // namespace road_east::assets\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--splash-png", type=Path, default=DEFAULT_SPLASH)
    parser.add_argument("--font-ttf", type=Path, default=DEFAULT_FONT_TTF)
    parser.add_argument("--data-dir", type=Path, default=DEFAULT_DATA_DIR)
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR)
    args = parser.parse_args()

    splash_out = args.out_dir / "splash_image.h"
    font16_out = args.out_dir / "font_8x16.h"
    font12_out = args.out_dir / "font_6x12.h"
    sprites_out = args.out_dir / "sprites_data.h"
    scenes_out = args.out_dir / "scenes_data.h"
    events_out = args.out_dir / "events_data.h"

    print(f"splash:  {args.splash_png} -> {splash_out}")
    build_splash_header(args.splash_png, splash_out)
    print(f"font:    {args.font_ttf} -> {font16_out}")
    build_font_header(args.font_ttf, font16_out, "8x16",
                      glyph_w=8, glyph_h=16, advance=8,
                      font_size=13, x_off=0, y_off=1)
    print(f"font:    {args.font_ttf} -> {font12_out}")
    # 7px cells stepped 6px apart. Size 11 rather than 12: at 12 some 28 glyphs
    # ('0', ы, ю, щ, Ж …) need the 7th column and visibly collide with the next
    # letter, at 11 only five do (Y g Ж ж м) and they merely touch.
    build_font_header(args.font_ttf, font12_out, "6x12",
                      glyph_w=7, glyph_h=12, advance=6,
                      font_size=11, x_off=0, y_off=0)

    sprites_doc = load_json(args.data_dir / "sprites.json")
    scenes_doc = load_json(args.data_dir / "scenes.json")
    events_doc = load_json(args.data_dir / "events.json")

    print(f"sprites: {args.data_dir / 'sprites.json'} -> {sprites_out}")
    sprite_index = build_sprites_header(sprites_doc, sprites_out)
    print(f"scenes:  {args.data_dir / 'scenes.json'} -> {scenes_out}")
    scene_index = build_scenes_header(scenes_doc, sprite_index, scenes_out)
    print(f"events:  {args.data_dir / 'events.json'} -> {events_out}")
    build_events_header(events_doc, scene_index, events_out)
    print("done.")


if __name__ == "__main__":
    main()
