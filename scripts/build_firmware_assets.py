# Namespace of the structs/sentinels in firmware/include/game_data_types.h.
DATA_NS = "road_east::data"


def rgb_to_565(r: int, g: int, b: int) -> int:
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def parse_css_color(value: object, context: str) -> int:
    """Convert a CSS hex color ("#rgb" or "#rrggbb") to RGB565."""
    if not isinstance(value, str) or not value.startswith("#"):
        raise SystemExit(f"{context}: expected CSS hex color, got {value!r}.")
    digits = value[1:]
    try:
        if len(digits) == 3:
            r, g, b = (int(d * 2, 16) for d in digits)
        elif len(digits) == 6:
            r, g, b = (int(digits[i : i + 2], 16) for i in (0, 2, 4))
        else:
            raise ValueError(value)
    except ValueError:
        raise SystemExit(f"{context}: malformed CSS hex color {value!r}.") from None
    return rgb_to_565(r, g, b)


def camel_case(name: str) -> str:
    """"walk_forest" -> "WalkForest", for building C++ identifiers."""
    parts = [p for p in re.split(r"[^0-9A-Za-z]+", name) if p]
    if not parts:
        raise SystemExit(f"Cannot derive a C++ identifier from {name!r}.")
    return "".join(p[:1].upper() + p[1:] for p in parts)


def c_string(value: str) -> str:
    """Escape a Python string into a C string literal (UTF-8 passthrough)."""
    out: list[str] = []
    for ch in value:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif ord(ch) < 0x20:
            out.append(f"\\{ord(ch):03o}")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def c_string_or_null(value: object, context: str) -> str:
    if value is None:
        return "nullptr"
    if not isinstance(value, str):
        raise SystemExit(f"{context}: expected a string, got {value!r}.")
    return c_string(value)


def check_i8(value: object, context: str) -> int:
    if not isinstance(value, int) or isinstance(value, bool) or not -128 <= value <= 127:
        raise SystemExit(f"{context}: {value!r} does not fit int8_t.")
    return value


def load_json(path: Path) -> object:
    # json.load builds plain dicts, which preserve key insertion order —
    # that order defines the sprite/scene indices baked below.
    if not path.exists():
        raise SystemExit(f"Data file not found: {path}")
    try:
        with path.open(encoding="utf-8") as f:
            return json.load(f)
    except json.JSONDecodeError as exc:
        raise SystemExit(f"{path}: invalid JSON: {exc}") from None


def write_header_preamble(
    f, generator_name: str, source: str, extra_includes: tuple[str, ...] = ()
) -> None:
    f.write("// AUTOGENERATED by scripts/build_firmware_assets.py — DO NOT EDIT.\n")
    f.write(f"// Source: {source}\n")
    f.write(f"// Regenerate via: python {generator_name}\n\n")
    f.write("#pragma once\n\n")
    f.write("#include <cstdint>\n")
    for include in extra_includes:
        f.write(f"#include {include}\n")
    f.write("\n")


def build_splash_header(png_path: Path, out_path: Path) -> None:
    img = Image.open(png_path)
    if img.mode != "P":
        raise SystemExit(
            f"{png_path}: expected mode 'P' (indexed), got '{img.mode}'."
        )
    palette = img.getpalette()
    if palette is None:
        raise SystemExit(f"{png_path}: no palette found.")

    # Determine how many palette entries are actually used.
    indices = list(img.tobytes())
    max_index = max(indices)
    if max_index > 15:
        raise SystemExit(
            f"{png_path}: uses {max_index + 1} colors; expected ≤ 16."
        )
    palette_len = 16
    rgb565 = []
    for i in range(palette_len):
        r, g, b = palette[i * 3 : i * 3 + 3]
        rgb565.append(rgb_to_565(r, g, b))

    w, h = img.size
    if w % 2 != 0:
        raise SystemExit(
            f"{png_path}: width must be even for 4bpp packing (got {w})."
        )

    # Pack two indices per byte (high nibble = left pixel).
    packed = bytearray(w * h // 2)
    for y in range(h):
        for x in range(0, w, 2):
            hi = indices[y * w + x] & 0xF
            lo = indices[y * w + x + 1] & 0xF
            packed[(y * w + x) // 2] = (hi << 4) | lo

    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w", encoding="utf-8") as f:
        write_header_preamble(
            f, "scripts/build_firmware_assets.py", str(png_path.relative_to(REPO_ROOT))
        )
        f.write("namespace road_east::assets {\n\n")
        f.write(f"constexpr int kSplashWidth = {w};\n")
        f.write(f"constexpr int kSplashHeight = {h};\n\n")
        f.write("// RGB565 palette (16 entries).\n")
        f.write("constexpr uint16_t kSplashPalette[16] = {\n")
        for i, c in enumerate(rgb565):
            sep = "," if i < 15 else ""
            f.write(f"    0x{c:04X}{sep}\n")
        f.write("};\n\n")
        f.write("// 4bpp packed pixel indices, row-major, high nibble = left pixel.\n")
        f.write(f"constexpr uint8_t kSplashPixels[{len(packed)}] = {{\n")
        for i in range(0, len(packed), 16):
            row = packed[i : i + 16]
            f.write("    " + ", ".join(f"0x{b:02X}" for b in row) + ",\n")
        f.write("};\n\n")
        f.write("}  // namespace road_east::assets\n")


# ---------------------------------------------------------------------------
# Fonts
# ---------------------------------------------------------------------------
# Codepoint ranges baked into the fonts:
#   0x20..0x7E  printable ASCII   (indices 0..94)
#   0x401       Ё                 (index 95)
#   0x410..0x44F А..я             (indices 96..159)
#   0x451       ё                 (index 160)
#   FONT_EXTRA  punctuation       (indices 161..)
#
# glyphIndex() in firmware/src/common/text_render.cpp mirrors this layout —
# keep the two in sync, and only ever append, so existing indices stay put.
# Typographic punctuation that Russian copy actually uses; without it the
# renderer silently substitutes a space.
FONT_EXTRA: list[int] = [
    0x00AB,  # «
    0x00BB,  # »
    0x2013,  # –
    0x2014,  # —
    0x2018,  # ‘
    0x2019,  # ’
    0x201C,  # “
    0x201D,  # ”
    0x2026,  # …
]

FONT_CODEPOINTS: list[int] = (
    list(range(0x20, 0x7F))
    + [0x401]
    + list(range(0x410, 0x450))
    + [0x451]
    + FONT_EXTRA
)


def rasterize_glyph(
    font: ImageFont.FreeTypeFont,
    cp: int,
    glyph_w: int,
    glyph_h: int,
    x_off: int,
    y_off: int,
) -> bytes:
    """Render one glyph into a glyph_w x glyph_h 1-bit bitmap.

    One byte per pixel row, MSB = leftmost pixel, glyph_h bytes per glyph.
    """
    img = Image.new("1", (glyph_w, glyph_h), 0)
    draw = ImageDraw.Draw(img)
    draw.text((x_off, y_off), chr(cp), font=font, fill=1)
    rows = bytearray(glyph_h)
    px = img.load()
    for y in range(glyph_h):
        b = 0
        for x in range(glyph_w):
            if px[x, y]:
                b |= 1 << (7 - x)
        rows[y] = b
    return bytes(rows)


def build_font_header(
    ttf_path: Path,
    out_path: Path,
    name: str,
    glyph_w: int,
    glyph_h: int,
    advance: int,
    font_size: int,
    x_off: int,
    y_off: int,
) -> None:
    """Rasterize FONT_CODEPOINTS into a glyph_w x glyph_h bitmap table.

    `advance` is the per-character cursor step and may be smaller than
    `glyph_w`: a handful of Cyrillic letters (ы, ю, щ) and '0' need one extra
    column of ink, and cutting the cell down to the advance clips them into a
    different letter. Letting them bleed into the neighbouring cell is the
    lesser evil — glyphs are drawn with a transparent background, so they
    merely touch.
    """
    if not ttf_path.exists():
        raise SystemExit(f"Font not found: {ttf_path}")
    if glyph_w > 8:
        raise SystemExit(
            f"font {name}: glyph width {glyph_w} breaks the one-byte-per-row encoding."
        )

    font = ImageFont.truetype(str(ttf_path), font_size)

    # Guard against silent clipping: a glyph whose ink is wider than the cell
    # renders as a different character, which is worse than a build failure.
    clipped = []
    for cp in FONT_CODEPOINTS:
        probe = Image.new("1", (glyph_w + 8, glyph_h + 8), 0)
        ImageDraw.Draw(probe).text((x_off, y_off), chr(cp), font=font, fill=1)
        box = probe.getbbox()
        if box is not None and (box[2] > glyph_w or box[3] > glyph_h):
            clipped.append(f"U+{cp:04X} {chr(cp)!r} ({box[2]}x{box[3]})")
    if clipped:
        raise SystemExit(
            f"font {name}: {len(clipped)} glyph(s) do not fit the {glyph_w}x{glyph_h} "
            f"cell at size {font_size}: {', '.join(clipped[:12])}"
        )

    glyph_data = bytearray()
    for cp in FONT_CODEPOINTS:
        glyph_data.extend(rasterize_glyph(font, cp, glyph_w, glyph_h, x_off, y_off))

    prefix = f"kFont{name}"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w", encoding="utf-8") as f:
        write_header_preamble(
            f, "scripts/build_firmware_assets.py", str(ttf_path)
        )
        f.write("namespace road_east::assets {\n\n")
        f.write(f"inline constexpr int {prefix}GlyphWidth = {glyph_w};\n")
        f.write(f"inline constexpr int {prefix}GlyphHeight = {glyph_h};\n")
        f.write(
            f"// Cursor step per character; may be < GlyphWidth, see the generator.\n"
        )
        f.write(f"inline constexpr int {prefix}GlyphAdvance = {advance};\n")
        f.write(f"inline constexpr int {prefix}GlyphCount = {len(FONT_CODEPOINTS)};\n\n")
        f.write(
            f"// Bitmap rows, MSB-first per row. {glyph_h} bytes per glyph, in the order\n"
            "// produced by the codepoint mapping in the .cpp companion.\n"
        )
        total = len(glyph_data)
        f.write(f"inline constexpr uint8_t {prefix}Glyphs[{total}] = {{\n")
        for i in range(0, total, glyph_h):
            row = glyph_data[i : i + glyph_h]
            f.write("    " + ", ".join(f"0x{b:02X}" for b in row))
            f.write(f",  // cp 0x{FONT_CODEPOINTS[i // glyph_h]:04X}\n")
        f.write("};\n\n")
        f.write("}  // namespace road_east::assets\n")


