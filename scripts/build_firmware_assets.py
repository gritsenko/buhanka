"""Generate C++ headers for ESP32 firmware from binary assets and game data.

Produces (into firmware/include/generated/):
  - splash_image.h
      16-color indexed splash (palette + 4bpp packed pixels) from
      assets/sprites/splash.png.
  - font_8x16.h / font_6x12.h
      Bitmap fonts with ASCII printable + Cyrillic glyphs, rasterized from a
      TTF (Consolas by default). Symbols are prefixed kFont8x16* / kFont6x12*.
  - sprites_data.h
      RGB565 pixel sheets + 1bpp opacity masks + the SpriteDef table, baked
      from data/sprites.json and the PNG sheets it references.
  - scenes_data.h
      SceneLayer / SceneDef tables baked from data/scenes.json.
  - events_data.h
      ChoiceDef / EventDef tables baked from data/events.json.

The sprite/scene/event tables brace-initialise the structs declared in
firmware/include/game_data_types.h in declared field order — that header is
the contract. Sprites and scenes are referenced by index everywhere; the
indices follow JSON insertion order, so the JSON files are read
order-preserving (the default dict behaviour of json.load).

Requires Pillow:
    pip install Pillow

Usage:
    python scripts/build_firmware_assets.py
    python scripts/build_firmware_assets.py --font-ttf C:/Windows/Fonts/consola.ttf
"""

